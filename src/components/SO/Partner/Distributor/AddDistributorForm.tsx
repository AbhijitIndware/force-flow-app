/* eslint-disable react-native/no-inline-styles */
// AddDistributorForm.tsx
import React from 'react';
import {Animated, View} from 'react-native';
import ReusableDropdown from '../../../ui-lib/resusable-dropdown';
import ReusableInput from '../../../ui-lib/reuseable-input';

interface Props {
  values: Record<string, string>;
  errors: Record<string, string>;
  touched: Record<string, boolean>;
  handleBlur: {
    (e: React.FocusEvent<any, Element>): void;
    <T = any>(fieldOrEvent: T): T extends string ? (e: any) => void : void;
  };
  handleChange: {
    (e: React.ChangeEvent<any>): void;
    <T_1 = string | React.ChangeEvent<any>>(
      field: T_1,
    ): T_1 extends React.ChangeEvent<any>
      ? void
      : (e: string | React.ChangeEvent<any>) => void;
  };
  setFieldValue: (field: string, value: any) => void;
  scrollY: Animated.Value;
  isEdit?: boolean;
  distributorGroupList: {label: string; value: string}[];
  zoneList: {label: string; value: string}[];
  stateList: {label: string; value: string}[];
  cityList: {label: string; value: string}[];

  onLoadMoreState?: () => void;
  loadingMoreState?: boolean;
  onLoadMoreZone?: () => void;
  loadingMoreZone?: boolean;
  onLoadMoreCity?: () => void;
  loadingMoreCity?: boolean;
  // 🔍 Search support
  zoneSearchText?: string;
  setZoneSearchText?: (text: string) => void;
  stateSearchText?: string;
  setStateSearchText?: (text: string) => void;
  citySearchText?: string;
  setCitySearchText?: (text: string) => void;

  distributorGroupSearchText?: string;
  setDistributorGroupSearchText?: (text: string) => void;
  onLoadMoreDistributorGroup?: () => void;
  loadingMoreDistributorGroup?: boolean;
}

const AddDistributorForm: React.FC<Props> = ({
  values,
  errors,
  touched,
  handleChange,
  handleBlur,
  setFieldValue,
  scrollY,
  isEdit = false,
  distributorGroupList,
  zoneList,
  stateList,
  cityList,
  onLoadMoreState,
  loadingMoreState,
  onLoadMoreZone,
  loadingMoreZone,
  onLoadMoreCity,
  loadingMoreCity,

  zoneSearchText,
  setZoneSearchText,
  stateSearchText,
  setStateSearchText,
  citySearchText,
  setCitySearchText,

  distributorGroupSearchText,
  setDistributorGroupSearchText,
  onLoadMoreDistributorGroup,
  loadingMoreDistributorGroup,
}) => {
  const onSelect = (field: string, val: string) => {
    setFieldValue(field, val);
    if (field === 'zone') {
      setFieldValue('state', '');
      setFieldValue('city', '');
    } else if (field === 'state') {
      setFieldValue('city', '');
    }
  };

  // Lists are paged, so a prefilled value may not be loaded yet: show it as is.
  const labelFor = (list: {label: string; value: string}[], value: string) =>
    list.find(item => item.value === value)?.label || value;

  return (
    <Animated.ScrollView
      onScroll={Animated.event([{nativeEvent: {contentOffset: {y: scrollY}}}], {
        useNativeDriver: false,
      })}
      scrollEventThrottle={16}
      style={{flex: 1}}
      contentContainerStyle={{padding: 16, paddingHorizontal: 21}}
      keyboardShouldPersistTaps="handled">
      {/* Distributor Name (Full Width) */}
      <ReusableInput
        label="Distributor Name"
        value={values.distributor_name}
        onChangeText={handleChange('distributor_name')}
        onBlur={() => handleBlur('distributor_name')}
        error={touched.distributor_name && errors.distributor_name}
      />

      {/* Distributor Group (Full Width) */}
      <ReusableDropdown
        label="Distributor Group"
        field="distributor_group"
        value={values.distributor_group}
        selectedLabel={labelFor(distributorGroupList, values.distributor_group)}
        data={distributorGroupList}
        error={touched.distributor_group && errors.distributor_group}
        onChange={(val: string) => onSelect('distributor_group', val)}
        onLoadMore={onLoadMoreDistributorGroup}
        loadingMore={loadingMoreDistributorGroup}
        searchText={distributorGroupSearchText}
        setSearchText={setDistributorGroupSearchText}
      />

      {/* SAP Code (Full Width). Distributor Code is generated by the server. */}
      <View style={{opacity: isEdit ? 0.6 : 1}}>
        <ReusableInput
          label="SAP Code"
          placeholder="Enter SAP code"
          value={values.distributor_sap_code}
          onChangeText={handleChange('distributor_sap_code')}
          onBlur={() => handleBlur('distributor_sap_code')}
          error={touched.distributor_sap_code && errors.distributor_sap_code}
          disabled={isEdit}
        />
      </View>

      {/* Zone (Full Width) */}
      <ReusableDropdown
        label="Zone"
        field="zone"
        value={values.zone}
        selectedLabel={labelFor(zoneList, values.zone)}
        data={zoneList}
        error={touched.zone && errors.zone}
        onChange={(val: string) => onSelect('zone', val)}
        onLoadMore={onLoadMoreZone}
        loadingMore={loadingMoreZone}
        searchText={zoneSearchText}
        setSearchText={setZoneSearchText}
      />

      {/* State (Full Width) */}
      <ReusableDropdown
        label="State"
        field="state"
        value={values.state}
        selectedLabel={labelFor(stateList, values.state)}
        data={stateList}
        error={touched.state && errors.state}
        onChange={(val: string) => onSelect('state', val)}
        onLoadMore={onLoadMoreState}
        loadingMore={loadingMoreState}
        searchText={stateSearchText}
        setSearchText={setStateSearchText}
      />

      {/* City (Full Width) */}
      <ReusableDropdown
        label="City"
        field="city"
        value={values.city}
        selectedLabel={labelFor(cityList, values.city)}
        data={cityList}
        error={touched.city && errors.city}
        onChange={(val: string) => onSelect('city', val)}
        onLoadMore={onLoadMoreCity}
        loadingMore={loadingMoreCity}
        searchText={citySearchText}
        setSearchText={setCitySearchText}
      />

      {/* Email and Mobile (2 Columns) */}
      <View style={{flexDirection: 'row', gap: 12, marginBottom: 12}}>
        <View style={{flex: 1}}>
          <ReusableInput
            label="Email"
            value={values.email}
            onChangeText={handleChange('email')}
            onBlur={() => handleBlur('email')}
            error={touched.email && errors.email}
            keyboardType="email-address"
          />
        </View>
        <View style={{flex: 1}}>
          <ReusableInput
            label="Mobile"
            value={values.mobile}
            onChangeText={handleChange('mobile')}
            onBlur={() => handleBlur('mobile')}
            error={touched.mobile && errors.mobile}
            keyboardType="numeric"
          />
        </View>
      </View>
    </Animated.ScrollView>
  );
};

export default AddDistributorForm;
